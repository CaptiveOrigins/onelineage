/**
 * Write made-up genotypes in the raw-data layouts the testing companies use, so importers can be tested.
 * The layouts follow the public descriptions of each company's download. Each file says it's made up.
 */
import type { Genotypes, Panel } from './genotypes.js'

export type RawFormat = 'ancestry' | '23andme' | 'myheritage' | 'ftdna' | 'livingdna'
export const RAW_FORMATS: readonly RawFormat[] = ['ancestry', '23andme', 'myheritage', 'ftdna', 'livingdna']

export function writeRaw(format: RawFormat, panel: Panel, g: Genotypes, generated = '2020-01-15'): string {
  const rows = panel.markers.map((m, i) => ({ m, call: g[i] as string }))
  switch (format) {
    case 'ancestry':
      return [
        '#AncestryDNA raw data download',
        `#This file was generated by AncestryDNA at: ${generated} 12:00:00 UTC`,
        '#Data was collected using AncestryDNA array version: V2.0',
        '#Data is formatted using AncestryDNA converter version: V1.0',
        '#MADE-UP TEST DATA: this file was generated by OneLineage for testing and describes no real person.',
        'rsid\tchromosome\tposition\tallele1\tallele2',
        ...rows.map(({ m, call }) => [m.rsid, m.chromosome, m.position, call === '--' ? '0' : call[0], call === '--' ? '0' : call[1]].join('\t')),
        '',
      ].join('\n')
    case '23andme':
      return [
        `# This data file generated by 23andMe at: ${generated}`,
        '# MADE-UP TEST DATA: this file was generated by OneLineage for testing and describes no real person.',
        '# We are using reference human assembly build 37 (also known as Annotation Release 104).',
        '# rsid\tchromosome\tposition\tgenotype',
        ...rows.map(({ m, call }) => [m.rsid, m.chromosome, m.position, call].join('\t')),
        '',
      ].join('\n')
    case 'myheritage':
      return [
        '##fileformat=MyHeritage',
        '##format=MHv1.0',
        '##chip=GSA',
        `##timestamp=${generated} 12:00:00`,
        '##reference=build37',
        '##made-up=generated by OneLineage for testing; describes no real person',
        'RSID,CHROMOSOME,POSITION,RESULT',
        ...rows.map(({ m, call }) => `"${m.rsid}","${m.chromosome}","${m.position}","${call}"`),
        '',
      ].join('\n')
    case 'ftdna':
      return ['RSID,CHROMOSOME,POSITION,RESULT', ...rows.map(({ m, call }) => `"${m.rsid}","${m.chromosome}","${m.position}","${call}"`), ''].join('\n')
    case 'livingdna':
      return [
        '# Living DNA customer genotype data download file version: 1.0.1',
        '# Human Genome Reference Build 37 (GRCh37.p13)',
        '# MADE-UP TEST DATA: generated by OneLineage for testing; describes no real person.',
        '# rsid\tchromosome\tposition\tgenotype',
        ...rows.map(({ m, call }) => [m.rsid, m.chromosome, m.position, call].join('\t')),
        '',
      ].join('\n')
  }
}
