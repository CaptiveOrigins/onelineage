/**
 * Raw DNA importer: the files people download from their own testing company. Downloading your own raw
 * DNA is the one export every DNA company's terms allowed when they were read on 2026-11-10, but the terms
 * register is still checked (`site_export`) before anything is read.
 *
 * Reads the AncestryDNA, 23andMe, MyHeritage, FamilyTreeDNA and Living DNA layouts. It records the test's
 * details where the file gives them (chip or array version, genome build, date), and checks every row.
 * A problem refuses the whole file. Nothing is guessed. A layout it doesn't recognise is refused, not read
 * as best it can.
 */
import { ImportRefused, type Issue, sha256Hex, SYNTHETIC_SOURCES, type TermsRegister } from '@captiveorigins/onelineage-core'

export type RawService = 'ancestry' | '23andme' | 'myheritage' | 'ftdna' | 'livingdna'

export type RawTestDetails = {
  service: RawService
  /** As the file states it, e.g. "AncestryDNA array version: V2.0" or "GSA". Null if the file doesn't say. */
  chip: string | null
  converter: string | null
  /** Genome build as stated by the file, e.g. "37". Null if the file doesn't say. */
  build: string | null
  /** When the company generated the file, as the file states it. */
  generated: string | null
  markers: number
  noCalls: number
  /** Chromosome labels present, normalised to "1"–"22", "X", "Y", "XY", "MT". */
  chromosomes: string[]
}

/** Calls per chromosome, in file order. Two letters, or "--" for no call. One letter is kept as is (X and Y in males). */
export type RawCalls = Map<string, { rsid: string[]; position: Int32Array; call: string[] }>

export type RawImport = {
  details: RawTestDetails
  calls: RawCalls
  file: string
  sha256: string
  notices: Issue[]
}

const ANCESTRY_CHR: Record<string, string> = { '23': 'X', '24': 'Y', '25': 'XY', '26': 'MT' }
const CALL = /^(--|[ACGTDI]{1,2})$/

function normaliseChromosome(service: RawService, c: string): string | null {
  const up = c.toUpperCase()
  if (service === 'ancestry' && ANCESTRY_CHR[up]) return ANCESTRY_CHR[up] as string
  if (/^([1-9]|1\d|2[0-2])$/.test(up)) return up
  if (up === 'X' || up === 'Y' || up === 'XY' || up === 'MT') return up
  if (up === '23') return 'X'
  if (up === '24') return 'Y'
  if (up === '25') return 'XY'
  if (up === '26' || up === 'M') return 'MT'
  return null
}

/** Recognise the company from the file's own header. Returns null if it can't tell, and the import is then refused. */
export function detectRawService(text: string): RawService | null {
  const head = text.slice(0, 4000)
  if (/^#AncestryDNA raw data download/m.test(head)) return 'ancestry'
  if (/^# This data file generated by 23andMe/m.test(head)) return '23andme'
  if (/^##fileformat=MyHeritage/m.test(head)) return 'myheritage'
  if (/^# Living DNA/m.test(head)) return 'livingdna'
  if (/^RSID,CHROMOSOME,POSITION,RESULT\s*$/m.test(head) && !/^#/m.test(head)) return 'ftdna'
  return null
}

export type RawInput = { file: string; bytes: Uint8Array; terms: TermsRegister; /** "planted" for made-up test files. */ source?: string }

export async function importRawDna(input: RawInput): Promise<RawImport> {
  const issues: Issue[] = []
  const err = (code: string, message: string, row?: number) => issues.push({ severity: 'error', code, message, file: input.file, ...(row ? { row } : {}) })
  let text: string
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(input.bytes)
  } catch {
    throw new ImportRefused([{ severity: 'error', code: 'file.encoding', message: 'not a text file; zipped downloads need unzipping first', file: input.file }])
  }
  const service = detectRawService(text)
  if (!service) throw new ImportRefused([{ severity: 'error', code: 'raw.layout', message: "this isn't a raw-data layout OneLineage recognises", file: input.file }])
  if (!SYNTHETIC_SOURCES.has(input.source ?? '')) input.terms.require(service, 'site_export')

  const meta = (re: RegExp) => re.exec(text.slice(0, 4000))?.[1]?.trim() ?? null
  const details: RawTestDetails = {
    service,
    chip:
      service === 'ancestry' ? meta(/^#Data was collected using (AncestryDNA array version: \S+)/m)
      : service === 'myheritage' ? meta(/^##chip=(.+)$/m)
      : null,
    converter: service === 'ancestry' ? meta(/^#Data is formatted using (AncestryDNA converter version: \S+)/m) : null,
    build:
      service === '23andme' ? meta(/build (\d+)/)
      : service === 'myheritage' ? meta(/^##reference=build(\d+)/m)
      : service === 'livingdna' ? meta(/Build (\d+)/)
      : null,
    generated:
      service === 'ancestry' ? meta(/^#This file was generated by AncestryDNA at: (.+)$/m)
      : service === '23andme' ? meta(/^# This data file generated by 23andMe at: (.+)$/m)
      : service === 'myheritage' ? meta(/^##timestamp=(.+)$/m)
      : null,
    markers: 0,
    noCalls: 0,
    chromosomes: [],
  }

  const calls: RawCalls = new Map()
  const lines = text.split(/\r?\n/)
  let headerSeen = false
  const seenRsid = new Set<string>()
  const pending = new Map<string, { rsid: string[]; position: number[]; call: string[] }>()
  lines.forEach((line, i) => {
    const row = i + 1
    if (line === '') return
    if (line.startsWith('#')) {
      if (/^# ?rsid\tchromosome\tposition\tgenotype$/i.test(line)) headerSeen = true
      return
    }
    if (!headerSeen) {
      if (/^rsid\tchromosome\tposition\tallele1\tallele2$/.test(line) || /^RSID,CHROMOSOME,POSITION,RESULT$/.test(line)) { headerSeen = true; return }
      err('raw.header', `expected the column header before data, found "${line.slice(0, 60)}"`, row)
      return
    }
    const f = service === 'myheritage' || service === 'ftdna' ? line.split(',').map((x) => x.replace(/^"|"$/g, '')) : line.split('\t')
    const [rsid, chr, pos, ...rest] = f
    const width = service === 'ancestry' ? 5 : 4
    if (f.length !== width || !rsid || !chr || !pos) { err('raw.width', `expected ${width} fields, found ${f.length}`, row); return }
    const c = normaliseChromosome(service, chr)
    if (!c) { err('raw.chromosome', `unknown chromosome "${chr}"`, row); return }
    const p = Number(pos)
    if (!Number.isInteger(p) || p < 0) { err('raw.position', `"${pos}" isn't a position`, row); return }
    let call = service === 'ancestry' ? (rest[0] === '0' && rest[1] === '0' ? '--' : `${rest[0]}${rest[1]}`) : (rest[0] as string)
    if (call === '00' || call === '') call = '--'
    if (!CALL.test(call)) { err('raw.call', `"${call}" isn't a genotype call`, row); return }
    if (seenRsid.has(rsid)) { err('raw.duplicate', `${rsid} appears twice`, row); return }
    seenRsid.add(rsid)
    let bucket = pending.get(c)
    if (!bucket) pending.set(c, (bucket = { rsid: [], position: [], call: [] }))
    bucket.rsid.push(rsid)
    bucket.position.push(p)
    bucket.call.push(call)
    details.markers++
    if (call === '--') details.noCalls++
  })
  if (!headerSeen) err('raw.header', 'no column header found')
  if (details.markers === 0) err('raw.empty', 'no genotype rows')
  if (issues.some((x) => x.severity === 'error')) throw new ImportRefused(issues)
  const order = (c: string) => (/^\d+$/.test(c) ? Number(c) : { X: 23, Y: 24, XY: 25, MT: 26 }[c] ?? 99)
  for (const [c, b] of [...pending].sort((a, z) => order(a[0]) - order(z[0]))) {
    calls.set(c, { rsid: b.rsid, position: Int32Array.from(b.position), call: b.call })
  }
  details.chromosomes = [...calls.keys()]
  const notices: Issue[] = []
  for (const k of ['chip', 'build', 'generated'] as const) {
    if (details[k] === null) notices.push({ severity: 'notice', code: `raw.no-${k}`, message: `the file doesn't state its ${k}; it's recorded as unknown`, file: input.file })
  }
  return { details, calls, file: input.file, sha256: await sha256Hex(input.bytes), notices }
}
